#include <stdio.h>   // gives us access to printf()

// this program’s whole job is to print "hello, world" on the screen.
// it’s the traditional first program in C.
int main(void) {
    printf("hello, world\n");  // print the message and move to a new line
    return 0;                  // tell the operating system everything went fine
}

